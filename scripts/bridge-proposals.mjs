#!/usr/bin/env node
/* Bridge the public proposal queue into the repository's review queue.
 *
 * The site and the machine interface accept proposals at POST /api/proposals. They land in the
 * hash-chained event log and wait for a human steward. Records, however, change only by commits
 * to records/. This script closes the gap: for every open proposal that does not yet have a
 * pull request, it writes proposals/<id>.json (the proposal plus its provenance and event hash),
 * runs the validator, and opens a DRAFT pull request on branch proposal/<id>. A named human
 * still has to turn the proposal into a record change and merge it; nothing here edits records/.
 *
 * Usage:  node scripts/bridge-proposals.mjs            (needs `gh` authenticated, a clean tree)
 *         node scripts/bridge-proposals.mjs --dry-run  (print what would happen)
 * Env:    HRM_API (default https://humanrepairmap.com/api)
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const API = process.env.HRM_API || "https://humanrepairmap.com/api";
const DRY = process.argv.includes("--dry-run");
const ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const REPO = process.env.GITHUB_REPOSITORY || "in-c0/human-repair-map";

const sh = (cmd, args, opts = {}) => execFileSync(cmd, args, { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], ...opts }).trim();
const log = (...a) => console.log("[bridge]", ...a);

/* ---- the graph, for naming the record a proposal targets ---- */
const graph = JSON.parse(readFileSync(join(ROOT, "public/graph/graph.json"), "utf8"));
const NODES = new Map(graph.nodes.map((n) => [n.id, n]));
const routes = (JSON.parse(readFileSync(join(ROOT, "data/cns-delivery.json"), "utf8")).routes || []);
function describeRecord(id) {
  const n = NODES.get(id) || NODES.get(`hrm:route/${id}`);
  if (n) {
    const slug = n.id.replace(/^hrm:/, "");
    const type = n.type;
    const file = type === "route" ? `data/cns-delivery.json` : type === "cell" ? `records/cells/${slug.split("/")[1]}.json` : `records/graph/${type}s/${slug.split("/")[1]}.json`;
    return { id: n.id, type, name: n.name || n.question || n.title || n.statement || n.id, api: `${API}/nodes/${n.id}`, file: existsSync(join(ROOT, file)) ? file : null, review: n.review ? n.review.state : "n/a" };
  }
  const r = routes.find((x) => x.id === id);
  if (r) return { id, type: "route", name: r.subject, api: `${API}/routes/${id}`, file: "data/cns-delivery.json", review: r.review || "ai-proposed" };
  return { id, type: "unknown", name: id, api: `${API}/nodes/${id}`, file: null, review: "unknown" };
}

/* ---- fetch the queue and the chain state ---- */
const proposals = (await (await fetch(`${API}/proposals`)).json()).proposals || [];
const verify = await (await fetch(`${API}/verify`)).json();
log(`${proposals.length} proposals in the public queue; chain ${verify.intact ? "intact" : "BROKEN"} at ${verify.events} events`);
if (!verify.intact) { console.error("Refusing to bridge from a broken event log."); process.exit(2); }

const open = proposals.filter((p) => p.state === "submitted" || p.state === "in-review");
const existingBranches = new Set(sh("git", ["ls-remote", "--heads", "origin", "proposal/*"]).split("\n").map((l) => l.split("\t")[1] || "").map((r) => r.replace("refs/heads/", "")).filter(Boolean));
const existingPRs = new Set(JSON.parse(sh("gh", ["pr", "list", "--repo", REPO, "--state", "all", "--search", "head:proposal/", "--json", "headRefName", "--limit", "200"])).map((p) => p.headRefName));

let made = 0;
for (const p of open) {
  const branch = `proposal/${p.id}`;
  if (existingBranches.has(branch) || existingPRs.has(branch) || existsSync(join(ROOT, "proposals", `${p.id}.json`))) { log(`skip ${p.id}: already bridged`); continue; }
  const rec = describeRecord(p.record_id);
  const actor = /^(ai|model|agent):/i.test(p.proposer || "") ? "ai" : "human";
  const doc = {
    $comment: "A public proposal, bridged from the API queue. Do not edit this file to resolve the proposal: change the record it targets and fill in `resolution`.",
    id: p.id,
    filed: p.created,
    kind: p.kind,
    target: rec,
    summary: p.summary,
    rationale: p.rationale,
    source_url: p.source_url || null,
    provenance: {
      proposedBy: { type: actor, name: p.proposer || "anonymous", affiliation: p.affil || null, verified: false },
      via: "POST /api/proposals",
      eventHash: p.event_hash,
      chainTip: verify.tip,
      chainEventsAtBridge: verify.events,
      verify: `${API}/verify`,
      queue: `${API}/proposals?record=${encodeURIComponent(p.record_id)}`
    },
    resolution: { state: "open", steward: null, date: null, verdict: null, recordEdits: [], note: null }
  };
  const body = [
    `## Proposal ${p.id} — ${p.kind}`,
    ``,
    `**${p.summary}**`,
    ``,
    p.rationale,
    ``,
    p.source_url ? `Source given: ${p.source_url}` : `No primary source was given.`,
    ``,
    `### Target record`,
    `- ${rec.name} (\`${rec.id}\`, ${rec.type}, review state: ${rec.review})`,
    `- API: ${rec.api}`,
    rec.file ? `- File: \`${rec.file}\`` : `- File: not found in records/ (a legacy or unknown id)`,
    ``,
    `### Provenance`,
    `- Filed ${p.created} via the public API by ${actor}: ${p.proposer || "anonymous"}${p.affil ? ` (${p.affil}, unverified)` : ""}`,
    `- Event hash \`${p.event_hash}\` in the hash-chained log (${verify.events} events, tip \`${String(verify.tip).slice(0, 16)}…\`, verify at ${API}/verify)`,
    `- This PR adds \`proposals/${p.id}.json\` and changes nothing else. It was opened by the bridge workflow, not by the proposer.`,
    ``,
    `### For the steward`,
    `1. Open the cited source and the target record. Decide: accept, dispute, or decline.`,
    `2. If accepting, edit the record file on this branch (rung, evidence, dependency, or a new claim/source with full provenance), run \`node scripts/build.mjs\`, and commit the regenerated files.`,
    `3. Fill in \`resolution\` in \`proposals/${p.id}.json\` (state, steward, date, verdict, recordEdits).`,
    `4. Mark the PR ready and merge. Declined proposals: fill in \`resolution\` with the reason and merge the JSON alone, so the decision is on the record.`,
    ``,
    `Research state only. Not a clinical tool. It does not diagnose, recommend treatments, or give advice about any person's illness.`
  ].join("\n");

  if (DRY) { log(`would open ${branch} for "${p.summary}" → ${rec.id}`); continue; }
  sh("git", ["checkout", "-q", "-B", branch, "origin/main"]);
  mkdirSync(join(ROOT, "proposals"), { recursive: true });
  writeFileSync(join(ROOT, "proposals", `${p.id}.json`), JSON.stringify(doc, null, 2) + "\n");
  let validation = "validator not run";
  try { sh("node", ["scripts/build.mjs"]); validation = "validator passed on this branch (records unchanged)"; }
  catch (e) { validation = "VALIDATOR FAILED on this branch:\n```\n" + String(e.stderr || e.stdout || e.message).slice(0, 1500) + "\n```"; }
  sh("git", ["add", "proposals"]);
  sh("git", ["-c", "user.name=hrm-bridge", "-c", "user.email=bridge@humanrepairmap.com", "commit", "-q", "-m", `proposal ${p.id}: ${p.kind} on ${rec.id}\n\nFiled via POST /api/proposals by ${actor}:${p.proposer || "anonymous"}. Event hash ${p.event_hash}.`]);
  sh("git", ["push", "-q", "-u", "origin", branch]);
  const url = sh("gh", ["pr", "create", "--repo", REPO, "--base", "main", "--head", branch, "--draft", "--title", `Proposal ${p.id}: ${p.kind} — ${p.summary.slice(0, 80)}`, "--body", body + "\n\n" + validation, "--label", "proposal"]);
  log(`opened ${url}`);
  made++;
}
if (!DRY) sh("git", ["checkout", "-q", "main"]);
log(`${made} pull request(s) opened, ${open.length - made} already bridged or skipped.`);
